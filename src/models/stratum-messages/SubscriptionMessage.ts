import { Expose, Transform } from 'class-transformer';
import { IsArray, IsString, MaxLength } from 'class-validator';

import { eRequestMethod } from '../enums/eRequestMethod';
import { EXTRANONCE2_SIZE_BYTES } from '../stratum.constants';
import { StratumBaseMessage } from './StratumBaseMessage';

export class SubscriptionMessage extends StratumBaseMessage {


    @IsArray()
    params: string[];

    @Expose()
    @IsString()
    @MaxLength(128)
    @Transform(({ value, key, obj, type }) => {
        return obj?.params?.[0] == null ? 'unknown' : SubscriptionMessage.refineUserAgent(obj.params[0]);
    })
    public userAgent: string;

    constructor() {
        super();
        this.method = eRequestMethod.SUBSCRIBE;
    }

    public response(clientId: string) {
        return {
            id: this.id,
            error: null,
            result: [
                [
                    ['mining.notify', clientId]
                ],
                clientId, //Extranonce1 -  Hex-encoded, per-connection unique string which will be used for coinbase serialization later. Keep it safe!
                EXTRANONCE2_SIZE_BYTES //Extranonce2_size - Represents expected length of extranonce2 which will be generated by the miner.
            ]
        }


    }

    public static refineUserAgent(userAgent: string): string {
        // Check the whole string first: Braiins OS sends
        // "2026-10-19-0-46be68fe-26.10-plus;bosminer-plus-tuner 0.9.0-46be68fe",
        // where the name only appears after a build date.
        if (userAgent.includes('bosminer') || userAgent.includes('bOS')) {
            return 'Braiins OS';
        }
        if (userAgent.includes('cpuminer')) {
            return 'cpuminer';
        }

        const refined = userAgent.split(' ')[0].split('/')[0].split('V')[0].split('-')[0];
        // If shortening leaves nothing or only a date/version number, keep the
        // first whole word instead (e.g. "Vnish/1.2" used to become "", now "Vnish").
        if (refined === '' || /^[\d.]+$/.test(refined)) {
            return userAgent.split(/[ ;/]/)[0];
        }
        return refined;
    }
}
